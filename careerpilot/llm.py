"""LLM layer (reasoning + writing). Everything that talks to Gemini lives here.

The agent receives an `llm_fn(context) -> dict`. To use another provider,
write a new function with the same signature and pass it to run_agent().

When no API key is available the module silently falls back to the built-in
rule-based synthesiser so the app always produces a complete guide.
"""
import json
import re

from .config import get_api_key, get_model_name


class LLMError(Exception):
    """Raised when the LLM is unavailable or returns unusable output."""


SYSTEM_RULES = """You are the synthesis step of an interview-preparation agent.
Rules:
- Only use topics from CANDIDATE_TOPICS (exact spelling). Order them by priority.
- Refer to research resources ONLY by their numeric id from RESOURCES. Never write URLs.
- Do not claim these resources cover every question a company has ever asked.
- Practice questions are generated by you, not sourced; keep them short and role-relevant.
- Respond with JSON only, matching exactly this shape:
{
  "target_job_summary": "2-3 sentences",
  "prioritized_topics": [{"topic": "...", "reason": "1 sentence", "resource_ids": [1]}],
  "preparation_strategy": ["step", "step", "step"],
  "practice_questions": [{"topic": "...", "question": "..."}]
}"""


def build_prompt(context):
    payload = {
        "JOB_TITLE": context["job_title"],
        "JOB_DESCRIPTION_EXCERPT": context["job_text"][:4000],
        "SKILLS_MATCHED_IN_RESUME": context["matched"],
        "SKILLS_NOT_EVIDENCED_IN_RESUME": context["missing"],
        "CANDIDATE_TOPICS": context["candidates"],
        "RESOURCES": context["resources"],
    }
    return SYSTEM_RULES + "\n\nINPUT:\n" + json.dumps(payload, indent=2, default=str)


def _call_gemini(prompt, api_key, model):
    """The only function that touches the network for the LLM (easy to mock)."""
    from google import genai
    from google.genai import types

    client = genai.Client(api_key=api_key)
    response = client.models.generate_content(
        model=model,
        contents=prompt,
        config=types.GenerateContentConfig(response_mime_type="application/json", temperature=0.3),
    )
    return response.text or ""


def parse_json_response(text):
    cleaned = re.sub(r"^```(?:json)?|```$", "", (text or "").strip(), flags=re.MULTILINE).strip()
    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError as exc:
        raise LLMError("The model did not return valid JSON.") from exc
    if not isinstance(data, dict):
        raise LLMError("The model returned JSON in an unexpected shape.")
    return data


def synthesize_with_gemini(context):
    """Call Gemini if a key is available; silently fall back to rule-based synthesis otherwise."""
    api_key = get_api_key()
    if not api_key:
        # No key present — use built-in synthesis without surfacing the missing key to the user
        return _rule_based_synthesize(context)
    try:
        text = _call_gemini(build_prompt(context), api_key, get_model_name())
    except LLMError:
        raise
    except Exception as exc:  # network error, bad key, quota, unknown model…
        raise LLMError(f"AI synthesis encountered an issue ({type(exc).__name__}). "
                       "Falling back to built-in analysis.") from exc
    return parse_json_response(text)


# ── built-in (rule-based) synthesis ──────────────────────────────────────────

def _rule_based_synthesize(context):
    """Deterministic synthesis used when no LLM is available.

    Produces a complete, useful guide from the skill-comparison data alone.
    Topics are ordered: gaps first (highest priority), then matched skills.
    Strategy and questions are templated but specific to the actual skills found.
    """
    cands    = context["candidates"]
    matched  = context["matched"]
    missing  = context["missing"]
    job      = context["job_title"]
    by_topic = {}
    for r in context["resources"]:
        by_topic.setdefault(r["topic"], []).append(r["id"])

    # Job summary — factual, based on extracted data
    if missing:
        gap_str = ", ".join(missing[:3]) + ("…" if len(missing) > 3 else "")
        summary = (
            f"This {job} role requires a broad technical skill set. "
            f"Key areas to focus on include {gap_str}. "
            f"Your resume already demonstrates {len(matched)} of the identified skills."
        )
    else:
        summary = (
            f"This {job} role aligns well with your existing skill set. "
            f"Your resume covers all {len(matched)} detected technical skills. "
            "Focus your preparation on deepening knowledge and practising articulation."
        )

    # Topics with specific reasons
    topics = []
    for t in cands:
        if t in missing:
            reason = f"{t} appears in the job description but was not detected in your resume — prioritise this gap."
        else:
            reason = f"{t} is listed in the job and matches your resume — refresh and prepare examples."
        topics.append({"topic": t, "reason": reason, "resource_ids": by_topic.get(t, [])})

    # Strategy — concrete, skill-aware steps
    strategy = []
    if missing:
        strategy.append(f"Start with your skill gaps: {', '.join(missing[:4])}. Spend at least 30 minutes on each.")
    if matched:
        strategy.append(f"Reinforce your strengths ({', '.join(matched[:3])}) by preparing a concrete project example for each.")
    strategy += [
        "For each topic, practise explaining the concept aloud in under 2 minutes without notes.",
        "Work through 2–3 practice questions per topic and write out your answers before the interview.",
        "Review any linked resources; prioritise official docs and recent articles.",
        "Do a full timed mock interview (45 min) 1–2 days before and note any gaps.",
    ]

    # Practice questions — templated but skill-specific
    question_templates = [
        "Can you walk me through a situation where you applied {skill} to solve a real problem?",
        "What are the core trade-offs you consider when working with {skill}?",
        "How would you explain {skill} to a non-technical colleague?",
        "Describe a bug or incident you debugged that involved {skill}. What was your process?",
        "How do you stay up to date with developments in {skill}?",
    ]
    questions = []
    for i, t in enumerate(cands):
        q_template = question_templates[i % len(question_templates)]
        questions.append({"topic": t, "question": q_template.format(skill=t)})

    return {
        "target_job_summary": summary,
        "prioritized_topics": topics,
        "preparation_strategy": strategy,
        "practice_questions": questions,
    }


def demo_synthesize(context):
    """Alias kept for backward-compatibility; delegates to rule-based synthesis."""
    return _rule_based_synthesize(context)
